-- Esquema do PanoCerto. Funciona no PostgreSQL e no H2 (modo PostgreSQL).

create table cooperativa (
    id bigint generated by default as identity primary key,
    nome varchar(120) not null
);

create table usuario (
    id bigint generated by default as identity primary key,
    nome varchar(120) not null,
    email varchar(160) not null unique,
    senha_hash varchar(100) not null,
    papel varchar(20) not null,
    cooperativa_id bigint not null references cooperativa (id)
);

create table produtor (
    id bigint generated by default as identity primary key,
    nome varchar(120) not null,
    telefone varchar(20) not null unique,
    cooperativa_id bigint not null references cooperativa (id)
);

create table talhao (
    id bigint generated by default as identity primary key,
    nome varchar(80) not null,
    hectares decimal(10, 2) not null,
    estadio varchar(4) not null,
    finalidade varchar(10) not null,
    produtor_id bigint not null references produtor (id),
    latitude double precision,
    longitude double precision,
    criado_em timestamp not null,
    ultimo_lembrete_em timestamp
);

create table monitoramento (
    id bigint generated by default as identity primary key,
    talhao_id bigint not null references talhao (id),
    data_hora timestamp not null,
    status varchar(12) not null,
    decisao varchar(12),
    media_percevejos double precision,
    media_lagartas double precision,
    media_desfolha double precision
);
create index idx_monitoramento_talhao on monitoramento (talhao_id, data_hora);

create table amostra (
    id bigint generated by default as identity primary key,
    monitoramento_id bigint not null references monitoramento (id),
    percevejos int not null,
    lagartas int not null,
    desfolha int not null,
    origem varchar(10) not null,
    url_midia varchar(300),
    transcricao varchar(2000),
    criada_em timestamp not null
);
create index idx_amostra_monitoramento on amostra (monitoramento_id);

create table aplicacao (
    id bigint generated by default as identity primary key,
    talhao_id bigint not null references talhao (id),
    data_hora timestamp not null,
    confirmada boolean not null
);

create table alerta (
    id bigint generated by default as identity primary key,
    talhao_id bigint not null references talhao (id),
    monitoramento_id bigint references monitoramento (id),
    criado_em timestamp not null,
    status varchar(12) not null,
    resolvido_em timestamp
);

create table mensagem_log (
    id bigint generated by default as identity primary key,
    produtor_id bigint references produtor (id),
    telefone varchar(20) not null,
    direcao varchar(10) not null,
    tipo varchar(12) not null,
    texto varchar(2000),
    opcoes varchar(1000),
    url_midia varchar(300),
    id_externo varchar(120),
    criada_em timestamp not null
);
create index idx_mensagem_telefone on mensagem_log (telefone, criada_em);

create table nivel_acao (
    id bigint generated by default as identity primary key,
    chave varchar(40) not null unique,
    descricao varchar(200) not null,
    valor double precision not null,
    unidade varchar(20) not null
);

create table conversa_estado (
    id bigint generated by default as identity primary key,
    telefone varchar(20) not null unique,
    produtor_id bigint references produtor (id),
    talhao_atual_id bigint references talhao (id),
    estado varchar(24) not null,
    pendente_percevejos int,
    pendente_lagartas int,
    pendente_origem varchar(10),
    pendente_url_midia varchar(300),
    pendente_transcricao varchar(2000),
    atualizada_em timestamp not null
);
